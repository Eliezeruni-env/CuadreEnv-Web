  t(key: string, params: Record<string, string | number> = {}): string {
    const currentLanguage = this.language();
    const translation =
      this.dictionaries[currentLanguage]?.[key] ??
      this.dictionaries.es?.[key] ??
      key;

    return Object.entries(params).reduce((result, [paramKey, value]) => {
      return result.replaceAll(`{${paramKey}}`, String(value));
    }, translation);
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(this.storageKey, language);
    }
  }

  private getInitialLanguage(): AppLanguage {
    if (typeof window === 'undefined') {
      return 'es';
    }

    const stored = window.localStorage.getItem(this.storageKey);
    return stored === 'en' ? 'en' : 'es';
  }

  getTranslatedNavItems(rawItems: INavData[]): INavData[] {
    return rawItems.map((item) => {
      const copy: INavData = {
        ...item,
        linkProps: {
          routerLinkActiveOptions: { exact: true },
          ...(item.linkProps || {})
        }
      };
      if (item.name) {
        const key = this.getNavKey(item.name);
        copy.name = this.t(key);
      }
      if (item.children) {
        copy.children = this.getTranslatedNavItems(item.children);
      }
      return copy;
    });
  }

  private getNavKey(name: string): string {
    switch (name) {
      case 'Dashboard':
        return 'nav.dashboard';
      case 'SaaS Core':
        return 'nav.saasCore';
      case 'Products':
      case 'Catálogo de Productos':
        return 'nav.products';
      case 'Inventory & Warehouses':
      case 'Inventario y Almacenes':
        return 'nav.inventory';
      case 'Sales Ledger':
      case 'Libro de Ventas':
        return 'nav.sales';
      case 'Customers Directory':
      case 'Directorio de Clientes':
        return 'nav.customers';
      case 'Accounting & Supply':
      case 'Contabilidad y Suministros':
        return 'nav.accountingSupply';
      case 'Purchases Log':
      case 'Registro de Compras':
        return 'nav.purchases';
      case 'Payments Ledger':
      case 'Historial de Pagos':
        return 'nav.payments';
      case 'Cash Register':
      case 'Caja Chica':
        return 'nav.cashRegister';
      case 'Administration':
      case 'Administración':
        return 'nav.administration';
      case 'Team & Users':
      case 'Equipo y Permisos':
        return 'nav.teamUsers';
      case 'Servicios':
        return 'nav.services';
      default:
        return name;
    }
  }
